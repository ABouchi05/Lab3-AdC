"""Generate hardwired program ROM and reset-loaded writable FF memory."""
import argparse
import hashlib
import json
import re
from pathlib import Path
from assembler import assemble

ROOT=Path(__file__).resolve().parents[1]

def generate(profile='final', destination=None, source_path=None):
    out=Path(destination) if destination else ROOT/'rtl/generated'
    out.mkdir(parents=True,exist_ok=True)
    source=Path(source_path or ROOT/'sw/game.s').read_text(encoding='utf-8-sig')
    if profile=='sim':
        values=dict(WAIT_CYCLES=3000,TENTH_CYCLES=1000,HOLD_CYCLES=2000,RELEASE_CYCLES=200)
        for name,value in values.items():
            source=re.sub(rf'(?m)^\.equ {name},.*$',f'.equ {name}, {value}',source)
    words,symbols=assemble(source)
    if not 1 <= len(words) <= 256:
        raise ValueError('ASIC instruction limit: 256 words')
    n=len(words); total=n+1
    cases='\n'.join(f"      32'd{i*4}: rom_word = 32'h{w:08x};" for i,w in enumerate(words))
    reset='\n'.join(f"        mem[{i}] <= 32'h{w:08x};" for i,w in enumerate(words+[0]))
    text=f'''// GENERATED by tools/generate.py, profile={profile}. Do not edit.
// {n} instruction words; one addressable scratch word; game uses zero scratch words.
module asic_memory #(parameter Unified=0) (
 input wire clk_i, rst_ni,
 input wire a_req_i, input wire [31:0] a_addr_i, output reg [31:0] a_rdata_o,
 input wire b_req_i, b_we_i, input wire [3:0] b_be_i,
 input wire [31:0] b_addr_i, b_wdata_i, output reg [31:0] b_rdata_o
);
 function [31:0] rom_word;
   input [31:0] address;
   begin
     case(address)
{cases}
       default: rom_word = 32'h00000013;
     endcase
   end
 endfunction
 generate if (Unified) begin : g_unified
   // No initial/readmemh. Each program bit is established by external reset.
   // Writable instruction storage prevents treating the program as immutable ROM.
   reg [31:0] mem [0:{total-1}];
   integer lane;
   always @(posedge clk_i or negedge rst_ni) begin
     if (!rst_ni) begin
{reset}
       a_rdata_o <= 0; b_rdata_o <= 0;
     end else begin
       if (a_req_i) a_rdata_o <= (a_addr_i < {total*4} && a_addr_i[1:0]==0) ? mem[a_addr_i[31:2]] : 32'h00000013;
       if (b_req_i) begin
         b_rdata_o <= (b_addr_i < {total*4} && b_addr_i[1:0]==0) ? mem[b_addr_i[31:2]] : 0;
         if (b_we_i && b_addr_i < {total*4} && b_addr_i[1:0]==0)
           for (lane=0;lane<4;lane=lane+1)
             if (b_be_i[lane]) mem[b_addr_i[31:2]][lane*8 +: 8] <= b_wdata_i[lane*8 +: 8];
       end
     end
   end
 end else begin : g_rom
   reg [31:0] scratch;
   integer lane;
   always @(posedge clk_i or negedge rst_ni) begin
     if (!rst_ni) begin
       scratch <= 0; a_rdata_o <= 0; b_rdata_o <= 0;
     end else begin
       // Combinational ROM followed by the original one-cycle response register.
       if (a_req_i) a_rdata_o <= rom_word(a_addr_i);
       if (b_req_i) begin
         b_rdata_o <= b_addr_i == {n*4} ? scratch :
                       b_addr_i < {n*4} ? rom_word(b_addr_i) : 0;
         if (b_we_i && b_addr_i == {n*4})
           for (lane=0;lane<4;lane=lane+1)
             if (b_be_i[lane]) scratch[lane*8 +: 8] <= b_wdata_i[lane*8 +: 8];
       end
     end
   end
 end endgenerate
endmodule
'''
    (out/'asic_memory.v').write_text(text,encoding='utf-8')
    (out/'game.hex').write_text(''.join(f'{w:08x}\n' for w in words))
    info=dict(profile=profile,instruction_words=n,instruction_bytes=n*4,
              data_words_used=0,data_words_provisioned=1,data_base=n*4,
              unified_words=total,source_sha256=hashlib.sha256(source.encode()).hexdigest(),symbols=symbols)
    (out/'program.json').write_text(json.dumps(info,indent=2))
    return info

if __name__=='__main__':
    p=argparse.ArgumentParser(); p.add_argument('--profile',choices=['final','sim'],default='final'); p.add_argument('--out')
    a=p.parse_args(); print(json.dumps(generate(a.profile,a.out),indent=2))
